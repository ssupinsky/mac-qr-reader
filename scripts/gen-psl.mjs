#!/usr/bin/env node
// Generates src/renderer/parsers/data/psl-rules.js from the bundled
// public_suffix_list.dat (the renderer cannot read files and there is no bundler).
//
//   node scripts/gen-psl.mjs           write the module
//   node scripts/gen-psl.mjs --check   exit 1 if the module is missing or stale
//
// Deterministic: output depends only on the .dat bytes. The .dat must match the
// pinned SHA-256 below (update it together with data/PSL-SOURCE.md when refreshing).
// Rules are converted to ASCII (punycode) form with Node's url.domainToASCII so the
// renderer can look up WHATWG `url.hostname` directly.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { domainToASCII } from 'node:url';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const PSL_SHA256 = '809adae1a2cb1621b70165c11e0d14412d3f104f40a4ebed9a99e23c54f78d71';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const datPath = path.join(root, 'src/renderer/parsers/data/public_suffix_list.dat');
const outPath = path.join(root, 'src/renderer/parsers/data/psl-rules.js');

function fail(msg) {
  console.error(`gen-psl: ${msg}`);
  process.exit(1);
}

/** Converts one PSL rule (Unicode, may start with "!" or contain "*" labels) to ASCII. */
function ruleToAscii(rule) {
  const exception = rule.startsWith('!');
  const body = exception ? rule.slice(1) : rule;
  const labels = body.split('.').map((label) => {
    if (label === '*') return '*';
    if (/^[\x21-\x7e]+$/.test(label)) return label.toLowerCase();
    const ascii = domainToASCII(label);
    if (!ascii) fail(`cannot convert rule label to ASCII: ${JSON.stringify(rule)}`);
    return ascii;
  });
  return (exception ? '!' : '') + labels.join('.');
}

export function generate(datBytes) {
  const sha = createHash('sha256').update(datBytes).digest('hex');
  if (sha !== PSL_SHA256) {
    fail(`SHA-256 mismatch for public_suffix_list.dat\n  expected ${PSL_SHA256}\n  actual   ${sha}`);
  }
  const text = datBytes.toString('utf8');
  const version = (text.match(/^\/\/ VERSION: (\S+)/m) || [])[1] || 'unknown';
  const commit = (text.match(/^\/\/ COMMIT: (\S+)/m) || [])[1] || 'unknown';

  const sections = { ICANN: [], PRIVATE: [] };
  let section = null;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    const marker = line.match(/^\/\/ ===(BEGIN|END) (ICANN|PRIVATE) DOMAINS===$/);
    if (marker) {
      section = marker[1] === 'BEGIN' ? marker[2] : null;
      continue;
    }
    if (!line || line.startsWith('//')) continue;
    if (!section) fail(`rule outside of a section: ${JSON.stringify(line)}`);
    // Per the PSL format, a rule ends at the first whitespace.
    sections[section].push(ruleToAscii(line.split(/\s/)[0]));
  }
  if (sections.ICANN.length < 1000 || sections.PRIVATE.length < 1000) fail('suspiciously few rules');

  return [
    '// GENERATED by scripts/gen-psl.mjs from public_suffix_list.dat — do not edit.',
    '//',
    '// Public Suffix List data. This Source Code Form is subject to the terms of the',
    '// Mozilla Public License, v. 2.0. If a copy of the MPL was not distributed with',
    '// this file, You can obtain one at https://mozilla.org/MPL/2.0/.',
    '// Source: https://publicsuffix.org/list/public_suffix_list.dat (see PSL-SOURCE.md).',
    '// Mechanically derived: comments removed, rules converted to ASCII (punycode).',
    '',
    `export const PSL_VERSION = ${JSON.stringify(version)};`,
    `export const PSL_COMMIT = ${JSON.stringify(commit)};`,
    `export const PSL_SHA256 = ${JSON.stringify(sha)};`,
    '',
    '/** Newline-separated rules of the ICANN section. */',
    `export const ICANN_RULES = ${JSON.stringify(sections.ICANN.join('\n'))};`,
    '',
    '/** Newline-separated rules of the PRIVATE section. */',
    `export const PRIVATE_RULES = ${JSON.stringify(sections.PRIVATE.join('\n'))};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!existsSync(datPath)) fail(`missing ${datPath}`);
  const output = generate(readFileSync(datPath));
  if (process.argv.includes('--check')) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (current !== output) fail('psl-rules.js is missing or stale; run node scripts/gen-psl.mjs');
    console.log('gen-psl: psl-rules.js is up to date');
  } else {
    writeFileSync(outPath, output);
    console.log(`gen-psl: wrote ${path.relative(root, outPath)} (${output.length} bytes)`);
  }
}
